import { writeFile, rename } from "node:fs/promises";
import { registry } from "../src/registry.js";
import { calibrationCases, grid } from "./data.js";
import { fitRelative } from "./metrics.js";
import { metadata, measureCases, saveJson } from "./runner.js";

const meta = metadata("calibration");
const cases = measureCases(calibrationCases());
const coefficients = {};
for (const [name, Atom] of registry) {
  const rows = cases.map(c => ({
    ...Atom.selection.features(c.shape), ms: c.timings[name].medianMs,
  }));
  coefficients[name] = fitRelative(rows);
}
await saveJson("calibration.json", { meta, grid, cases });
await saveJson("model.json", coefficients);
const calibrationModule = new URL("../src/calibration.js", import.meta.url);
const temporaryModule = new URL("../src/calibration.tmp.js", import.meta.url);
const header = "// Generated by npm run calibrate. Units: milliseconds per feature unit.\n";
await writeFile(temporaryModule, header + "export const coefficients = " + JSON.stringify(coefficients, null, 2) + ";\n");
await rename(temporaryModule, calibrationModule);
process.stdout.write("Calibrated " + registry.size + " atoms on " + cases.length + " cases. Run ID " + meta.id + "\n");
